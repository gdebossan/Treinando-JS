const diaDaSemana = "Xablau";

switch (diaDaSemana) {
  case "Domingo":
    console.log("Estamos no Domingo - Dia 1");
    break;
  case "Segunda":
    console.log("Estamos na Segunda - Dia 2");
    break;
  case "Terca":
    console.log("Estamos na Terca - Dia 3");
    break;
  case "Quarta":
    console.log("Estamos na Quarta - Dia 4");
    break;
  case "Quinta":
    console.log("Estamos na Quinta - Dia 5");
    break;
  case "Sexta":
    console.log("Estamos na Sexta - Dia 6");
    break;
  case "Sabado":
    console.log("Estamos na Sabado - Dia 7");
    break;
  default:
    console.log("Esse dia nao existe");
}
